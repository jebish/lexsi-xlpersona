import argparse
import json
from pathlib import Path

BANNED = {"reply", "raw"}
LABEL_KEYS = ("id", "cond", "guardrail", "set", "template", "safety", "refusal", "unsafe_coherent", "refused",
              "degenerate", "plausible")


def build_release_tables(rows, templates, out_dir, summary):
    from xlpersona.conditions import CONDITIONS
    from xlpersona.prompts import stage1_prompt_sets, stage2_prompt_sets

    cat = {r["id"]: r.get("category") for r in rows}
    seen, prompts = set(), []

    def add(p):
        if (p.id, p.cond, p.template) not in seen:
            seen.add((p.id, p.cond, p.template))
            prompts.append({"id": p.id, "cond": p.cond, "template": p.template, "split": p.split,
                            "harmful": p.harmful, "category": cat.get(p.id), "prompt": p.text})

    for p in stage1_prompt_sets(rows, templates):
        add(p)
    for c in CONDITIONS:
        for ps in stage2_prompt_sets(rows, templates, c).values():
            for p in ps:
                add(p)
    labels = []
    for path in sorted(Path(out_dir).glob("*/*.jsonl")):
        cell = path.stem.split("__")[0]
        for line in path.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            labels.append({k: (cell if k == "set" else r.get(k)) for k in LABEL_KEYS})
    for table in (prompts, labels):
        for row in table:
            if BANNED & set(row):
                raise ValueError(f"refusing to release a {BANNED & set(row)} column")
    return {"prompts": prompts, "labels": labels, "results": summary}


def dataset_card(tables, curation, judge, review):
    n_p, n_l = len(tables["prompts"]), len(tables["labels"])
    kappa = ("Judge agreement with a native speaker's labels on 150 replies (Cohen's kappa, safety): " +
             ", ".join(f"{k} {v['cohen_kappa']:.3f}" for k, v in judge["safety"].items() if v["cohen_kappa"] is not None))
    flagged = ", ".join(f"{k.split('/')[1]} {v['wrong']}/{v['n']}" for k, v in review.items()
                        if k.startswith("item/") and k.endswith("/random"))
    return f"""---
license: cc-by-nc-4.0
language: [en, hi, ne]
tags: [jailbreak, persona, multilingual, romanization, code-mixing, safety]
configs:
- config_name: prompts
  data_files: prompts/train-*
- config_name: labels
  data_files: labels/train-*
---
# persona-jailbreak-7c

Persona-jailbreak prompts in seven conditions (English; Hindi and Nepali in native script, romanized, and
code-mixed with English) and per-item safety labels for Tiny Aya Global under 14 guardrails.

* `prompts` ({n_p} rows): every evaluated prompt (plain requests and persona-wrapped harmful requests).
* `labels` ({n_l} rows): per prompt x guardrail: Qwen3Guard's verdicts (`safety`: Safe, Controversial or Unsafe;
  `refusal`), and the derived unsafe-and-coherent, refused, degenerate and plausible-script flags.
* `results/summary.json`: aggregate tables (unsafe rates with Wilson CIs, McNemar tests, transfer map, MMLU).

Model replies are withheld because some contain harmful content. Greedy decoding makes them reproducible from
the released prompts, model, directions and code.

Sources: harmful/benign requests from JailbreakBench (MIT); Hindi/Nepali Devanagari text machine-translated
with NLLB-200 1.3B; romanized and code-mixed variants generated by {curation.get('generator')} and gated with CuratorKIT
(LLM-judge reward >= 0.75, script, length and target-language checks, two feedback repair rounds); items that
still failed were rewritten outside the generator (`meta.source = manual` in the repo's `data/requests.jsonl`). Per-condition
counts: {json.dumps(curation.get('full_run', {}).get('final_source', {}))}.
Native-speaker review: random variants flagged per form: {flagged}. All rewritten variants and reviewed
templates were correct, as was the Devanagari behind every corrected variant.
{kappa}

Licence: CC-BY-NC-4.0 (labels are derived from Tiny Aya outputs; Tiny Aya is CC-BY-NC).
Research use only: the prompts request harmful content and exist to evaluate safeguards.
"""


def push(tables, repo, card):
    from datasets import Dataset
    from huggingface_hub import HfApi

    for name in ("prompts", "labels"):
        Dataset.from_list(tables[name]).push_to_hub(repo, config_name=name, split="train")
    api = HfApi()
    api.upload_file(path_or_fileobj=json.dumps(tables["results"], indent=1).encode(), path_in_repo="results/summary.json",
                    repo_id=repo, repo_type="dataset")
    api.upload_file(path_or_fileobj=card.encode(), path_in_repo="README.md", repo_id=repo, repo_type="dataset")


if __name__ == "__main__":
    from xlpersona.data import load_requests
    from xlpersona.templates import load_templates

    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--push")
    a = ap.parse_args()
    summary = json.loads(Path("results/summary.json").read_text(encoding="utf-8"))
    curation = json.loads(Path("results/curation_summary.json").read_text(encoding="utf-8"))
    judge = json.loads(Path("results/judge_validation_final_qwen.json").read_text(encoding="utf-8"))
    review = json.loads(Path("results/robustness_clean_forms.json").read_text(encoding="utf-8"))["prompt_review"]
    t = build_release_tables(load_requests(), load_templates(), a.out_dir, summary)
    card = dataset_card(t, curation, judge, review)
    print(len(t["prompts"]), "prompts,", len(t["labels"]), "labels")
    if a.push:
        push(t, a.push, card)
        print("pushed", a.push)
    else:
        Path("out/dataset_card.md").write_text(card, encoding="utf-8")
        print("dry run; card at out/dataset_card.md")
